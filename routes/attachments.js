"use strict";
const router = require("express").Router();
const { authenticateUser } = require("../middleware/authMiddleware");
const upload = require("../middleware/upload");
const c = require("../controllers/attachmentsController");
router.use(authenticateUser);
router.get("/download", c.pathDownload);
router.get("/download/:filename", c.pathDownload);
router.get("/:id/download", c.download);
router.get("/item/:itemId", c.listItem);
router.post("/item/:itemId", upload.any(), c.uploadItem);
router.get("/:requestId", c.listRequest);
router.post("/:requestId", upload.any(), c.uploadRequest);
router.delete("/:id", c.remove);
module.exports = router;
