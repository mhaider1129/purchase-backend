SELECT count(*) AS invalid_institute_references FROM inventory_transactions it
 WHERE it.institute_id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM institutes i WHERE i.id = it.institute_id);
SELECT count(*) AS invalid_zero_allocations FROM inventory_transaction_allocations WHERE quantity = 0;
SELECT count(*) AS orphan_movement_allocations FROM inventory_transaction_allocations a
 WHERE NOT EXISTS (SELECT 1 FROM inventory_transactions it WHERE it.id = a.inventory_transaction_id);
SELECT it.id, it.quantity AS movement_quantity, count(a.id) AS allocation_count,
       COALESCE(sum(a.quantity), 0) AS allocation_quantity
  FROM inventory_transactions it
  LEFT JOIN inventory_transaction_allocations a ON a.inventory_transaction_id = it.id
 WHERE it.metadata->>'allocationLedgerVersion' = '1'
 GROUP BY it.id, it.quantity
HAVING count(a.id) = 0 OR COALESCE(sum(a.quantity), 0) <> it.quantity;