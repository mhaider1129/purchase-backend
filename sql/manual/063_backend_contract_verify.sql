SELECT 'review'::text AS category,'demand_planning_ui_policy'::text AS check_name,COUNT(*)::bigint AS finding_count,COALESCE(jsonb_agg(issue),'[]'::jsonb) AS details FROM (SELECT 'feature.demandPlanning retains a saved policy that differs from current backend defaults; optional SQL 062 aligns only the exact supplied empty policy' AS issue FROM public.ui_resource_permissions WHERE resource_key='feature.demandPlanning' AND (permissions IS DISTINCT FROM ARRAY['planning.view','planning.manage','replenishment.manage']::text[] OR require_all IS DISTINCT FROM false)) finding
) report ORDER BY category,check_name;
